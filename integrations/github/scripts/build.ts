/**
 * Build the integration from src/:
 *  - server.ts: a self-contained bundle of src/ (what VoiceOS runs, and the one
 *    file the Integration Studio carries when it reopens a draft)
 *  - voiceos.integration.json: tools, schemas and descriptions taken from the
 *    running server's tools/list; confirmation cards from src/confirmations.ts
 *  - voiceos.integration.preview.json and the Studio's preview fixtures
 *
 *   bun run build
 *
 * Reload the integration in VoiceOS afterwards.
 */
import { Client } from "@modelcontextprotocol/sdk/client/index.js";
import { InMemoryTransport } from "@modelcontextprotocol/sdk/inMemory.js";
import { randomBytes } from "node:crypto";
import { existsSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { FACADES, TOOL_META, WRITE_TOOLS } from "../src/catalog.ts";
import { buildConfirmation } from "../src/confirmations.ts";
import { Gateway } from "../src/gateway.ts";
import { createServer } from "../src/mcpServer.ts";
import { SOC2_REVIEW_WARNING } from "../src/reviewWarning.ts";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const manifestPath = join(root, "voiceos.integration.json");
const existing = JSON.parse(readFileSync(manifestPath, "utf8"));

// 1. server.ts bundle -------------------------------------------------------
// One self-contained file. A shared install is just the five packaged files,
// with no node_modules, and Bun's automatic install takes the latest release
// for a bare import (zod 4.6.7, not the pinned 3.25.76, on 2026-10-28) and
// fails on version-pinned ones. Inlining the dependencies means bringing in
// code that compiles JavaScript from strings, which VoiceOS's share review
// rejects, so the build switches it off:
//  - zod 4 (used inside the MCP SDK) generates fast object parsers with
//    `new Function` when it can; told it can't, it parses normally.
//  - The SDK's JSON Schema validator is ajv, a code generator. It only runs
//    for tool output schemas (Composio's tools declare none) and elicitation
//    (unused), so it becomes a validator that refuses if it is ever reached.
const PATCHES: Array<{ file: RegExp; from: string; to: string }> = [
  {
    file: /node_modules\/zod\/v4\/core\/util\.js$/,
    from: '    try {\n        const F = Function;\n        new F("");\n        return true;\n    }\n    catch (_) {\n        return false;\n    }',
    to: "    return false;",
  },
  {
    file: /node_modules\/zod\/v4\/core\/doc\.js$/,
    from: "        const F = Function;\n        const args = this?.args;\n        const content = this?.content ?? [``];\n        const lines = [...content.map((x) => `  ${x}`)];\n        // console.log(lines.join(\"\\n\"));\n        return new F(...args, lines.join(\"\\n\"));",
    to: '        throw new Error("zod code generation is disabled in this build");',
  },
];
const NO_AJV = `export class AjvJsonSchemaValidator {
  getValidator() {
    return () => ({ valid: false, data: undefined, errorMessage: "JSON Schema validation isn't available in this build." });
  }
}
`;
const bundle = await Bun.build({
  entrypoints: [join(root, "src/main.ts")],
  target: "bun",
  format: "esm",
  minify: false,
  plugins: [
    {
      name: "no-code-from-strings",
      setup(build) {
        build.onLoad({ filter: /@modelcontextprotocol\/sdk\/dist\/esm\/validation\/ajv-provider\.js$/ }, () => ({ contents: NO_AJV, loader: "js" }));
        for (const p of PATCHES) {
          build.onLoad({ filter: p.file }, async (args) => {
            const source = await Bun.file(args.path).text();
            if (source.split(p.from).length !== 2) throw new Error(`${args.path} changed; review the build's patch for it.`);
            return { contents: source.replace(p.from, p.to), loader: "js" };
          });
        }
      },
    },
  ],
});
if (!bundle.success) {
  for (const log of bundle.logs) console.error(log);
  process.exit(1);
}
const header = `// GENERATED by \`bun run build\` from src/ — edit src/ and rebuild; don't edit this file.\n// GitHub for VoiceOS, through Composio. Source of truth: src/main.ts.\n`;
const code = await bundle.outputs[0].text();
if (/\bnew\s+Function\s*\(|=\s*Function\b|(?<![\w.$])Function\s*\(|(?<![\w.$])eval\s*\(/.test(code)) throw new Error("server.ts would compile code from strings; VoiceOS's share review rejects that.");
// Bun's "// @bun" pragma only counts on the first line, so the header goes after it.
const pragma = code.startsWith("// @bun") ? `${code.slice(0, code.indexOf("\n") + 1)}` : "";

// 2. tools/list from the real server ----------------------------------------
const scratch = mkdtempSync(join(tmpdir(), "gh-build-"));
const gateway = new Gateway({
  baseUrl: "http://127.0.0.1:9", connectionEnabled: true, stateDir: scratch, poll: false, auditFile: false,
});
const [serverSide, clientSide] = InMemoryTransport.createLinkedPair();
await createServer(gateway).connect(serverSide);
const client = new Client({ name: "voiceos-build", version: "1.0.0" });
await client.connect(clientSide);
const { tools: live } = await client.listTools();
await client.close();
rmSync(scratch, { recursive: true, force: true });

const tools = FACADES.map((name) => {
  const tool = live.find((t) => t.name === name);
  if (!tool) throw new Error(`server doesn't register ${name}`);
  const { $schema: _schema, ...inputSchema } = tool.inputSchema as Record<string, unknown>;
  return {
    name,
    title: TOOL_META[name].title,
    description: tool.description,
    inputSchema,
    ...(WRITE_TOOLS.has(name)
      ? { hidePermissionToggle: true, confirmation: buildConfirmation(name as never) }
      : {}),
  };
});

