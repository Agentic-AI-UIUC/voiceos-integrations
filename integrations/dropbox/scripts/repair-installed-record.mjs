import {readFile,writeFile,copyFile,rename,access} from 'node:fs/promises';
import {execFileSync} from 'node:child_process';
import {join,resolve} from 'node:path';
import assert from 'node:assert/strict';
const appData=process.env.APPDATA;
if(!appData) throw new Error('APPDATA is required on Windows');
const configPath=process.env.VOICEOS_CONFIG_PATH||join(appData,'VoiceOS','config.json');
const bytes=await readFile(configPath);
const config=JSON.parse(bytes.toString('utf8'));
const matches=(config.installedIntegrations||[]).filter(x=>x.manifest?.id==='com.voiceos.generated.dropbox');
assert.equal(matches.length,1,'Expected exactly one installed Dropbox record');
const entry=matches[0];
const dir=resolve(entry.dirPath);
assert.match(dir,/\\VoiceOS\\custom-mcps\\dropbox-[a-z0-9]+$/i);
await access(join(dir,'AGENTS.md'));
const manifest=JSON.parse(await readFile(join(dir,'voiceos.integration.json'),'utf8'));
const pkg=JSON.parse(await readFile(join(dir,'package.json'),'utf8'));
assert.equal(manifest.id,entry.manifest.id);
const release=JSON.parse(await readFile(new URL('../source/portable/voiceos.integration.json',import.meta.url),'utf8'));
assert.equal(manifest.version,release.version);assert.equal(pkg.version,manifest.version);
assert.equal(manifest.tools.length,14);
assert.deepEqual(manifest.runtime,entry.manifest.runtime,'Runtime must not change');
const server=(config.customMcpServers||[]).find(x=>x.id===entry.serverId);
assert.ok(server,'Missing matching Dropbox server record');
assert.equal(server.integrationId,manifest.id);
assert.equal(resolve(server.cwd),dir);
const writes=manifest.tools.filter(t=>t.confirmation).map(t=>t.name);
assert.equal(writes.length,8);
assert.ok(Array.isArray(server.confirmTools),'Unexpected confirmation storage format');
const oldVersion=entry.manifest.version,oldCount=entry.manifest.tools.length;
const original=structuredClone(config);
entry.manifest=manifest;
server.confirmTools=[...new Set([...server.confirmTools,...writes])];
assert.equal(manifest.icon,'icon.png','Unexpected icon path');
server.iconDataUrl='data:image/png;base64,'+(await readFile(join(dir,'icon.png'))).toString('base64');
// Credentials, IDs, enablement, launch configuration, and all unrelated settings stay byte-value equivalent.
const roundTrip=structuredClone(config);
roundTrip.installedIntegrations.find(x=>x.serverId===entry.serverId).manifest=original.installedIntegrations.find(x=>x.serverId===entry.serverId).manifest;
roundTrip.customMcpServers.find(x=>x.id===server.id).confirmTools=original.customMcpServers.find(x=>x.id===server.id).confirmTools;
roundTrip.customMcpServers.find(x=>x.id===server.id).iconDataUrl=original.customMcpServers.find(x=>x.id===server.id).iconDataUrl;
assert.deepEqual(roundTrip,original,'Unexpected change outside Dropbox manifest/confirmations/icon');
console.log(`Dropbox cached manifest: ${oldVersion}/${oldCount} actions -> ${manifest.version}/${manifest.tools.length} actions; ${writes.length} writes require confirmation. Credentials and unrelated settings preserved.`);
if(process.argv.includes('--apply')){
 const count=Number(execFileSync('powershell.exe',['-NoProfile','-Command','@(Get-Process -Name VoiceOS -ErrorAction SilentlyContinue).Count'],{encoding:'utf8',windowsHide:true}).trim());
 assert.equal(count,0,'Fully quit VoiceOS before repairing its saved record');
 assert.ok((await readFile(configPath)).equals(bytes),'Config changed during preparation; rerun against latest state');
 const stamp=new Date().toISOString().replace(/[:.]/g,'-');
 const backup=configPath+'.before-dropbox-record-'+stamp+'.bak';
 await copyFile(configPath,backup);
 const temp=configPath+'.dropbox-repair-'+stamp+'.tmp';
 await writeFile(temp,JSON.stringify(config,null,2)+'\n',{mode:0o600});
 assert.ok((await readFile(configPath)).equals(bytes),'Config changed before commit; original left untouched');
 await rename(temp,configPath);
 const saved=JSON.parse(await readFile(configPath,'utf8'));
 assert.deepEqual(saved,config);
 console.log('Saved and verified the Dropbox installed record; backup created beside config.json.');
}else console.log('Dry run only; no files changed.');
