writeFileSync(join(root, "server.ts"), pragma + header + code.slice(pragma.length));
writeFileSync(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`);

// 4. Preview fixtures ------------------------------------------------------
// Reads use public repositories. Writes point at a sandbox name and only ever
// run against verify.ts's local fake Composio — never a real account.
const fixtures: Record<string, Record<string, unknown>> = {
  get_issue: { owner: "octocat", repo: "Hello-World", issue_number: 1 },
  list_pull_requests: { owner: "octocat", repo: "Hello-World", state: "open" },
  search_repositories: { q: "voice assistant language:typescript stars:>100" },
  search_code: { q: "addClass repo:jquery/jquery" },
  create_issue: { owner: "voiceos-test", repo: "sandbox", title: "VoiceOS preview issue", body: "Created by the VoiceOS preview harness." },
  update_issue: { owner: "voiceos-test", repo: "sandbox", issue_number: 1, state: "closed", state_reason: "completed" },
  create_issue_comment: { owner: "voiceos-test", repo: "sandbox", issue_number: 1, body: "Preview comment from VoiceOS." },
  create_pull_request_review: { owner: "voiceos-test", repo: "sandbox", pull_number: 2, event: "COMMENT", body: "Preview review comment from VoiceOS." },
};
writeFileSync(
  join(root, "voiceos.integration.preview.json"),
  `${JSON.stringify(
    {
      schemaVersion: 1,
      description: "Development-only sample inputs for bun verify.ts and Studio previews. Writes run only against verify.ts's local fake Composio.",
      tools: Object.fromEntries(FACADES.map((name) => [name, { args: fixtures[name], expectedGlanceBlocks: 1 }])),
    },
    null,
    2,
  )}\n`,
);

const studioPath = join(root, "studio-meta.json");
if (existsSync(studioPath)) {
  const studio = JSON.parse(readFileSync(studioPath, "utf8"));
  studio.preview = {
    utterances: [
      "What's issue 1 in octocat's Hello-World repo?",
      "Show the open pull requests in octocat's Hello-World",
      "Where is addClass defined in jquery's jquery repo?",
    ],
    toolPreviews: FACADES.filter((name) => !WRITE_TOOLS.has(name)).map((name) => ({ tool: name, sampleArgs: fixtures[name] })),
  };
  studio.updatedAt = new Date().toISOString();
  writeFileSync(studioPath, `${JSON.stringify(studio, null, 2)}\n`);
}

